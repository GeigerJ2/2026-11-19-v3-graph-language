"""Combine canonical source regions for Slidev's native Python syntax highlighting."""

import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXCERPTS = {
    'declared_failures.py': ('s21_division_task.py', 's22_declared_failure.py'),
    'retry_loop.py': ('s21_division_task.py', 's24_retry_loop.py'),
    'placements.py': ('s15_placement_task.py', 's16_placements.py'),
}


def combined_source(files: tuple[str, ...]) -> str:
    """Join displayed regions without duplicating their canonical implementations.

    :param files: source files containing an ``example`` region.
    :return: a generated Python excerpt with region markers for Slidev.
    """
    regions = []
    for filename in files:
        source = (HERE / filename).read_text()
        body = source.split('# region example\n', 1)[1].split('# endregion example', 1)[0].strip()
        regions.append(body)
    typing_note = '# mypy: disable-error-code=name-defined\n' if 's16_placements.py' in files else ''
    return (
        '# Generated by sync_slide_code.py; edit the source snippets instead.\n' + typing_note + '# ruff: noqa\n'
        '# fmt: off\n'
        '# region example\n'
        'from aiida.engine import graph\n\n' + '\n\n\n'.join(regions) + '\n# endregion example\n'
    )


def sync(*, check: bool = False) -> None:
    """Generate merged excerpts, or fail if they no longer match the canonical sources.

    :param check: validate without modifying files.
    """
    for name, files in EXCERPTS.items():
        target = HERE / 'generated' / name
        expected = combined_source(files)
        if check:
            assert target.is_file() and target.read_text() == expected, (
                f'{target} is stale; run scripts/sync_slide_code.py'
            )
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected)
            print(target)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sync(check=args.check)
